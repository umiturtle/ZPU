#!/usr/bin/env python3
"""Generates `src/zui/font_data.zig`: a small antialiased ASCII bitmap font.

This script is *not* part of the build. Its output is committed, and `zig build`
never runs Python — the script is kept so the data can be regenerated and
audited. It rasterises the scalable font Pillow ships (an Aileron/DejaVu-class
sans-serif) at the master size below into 1 byte of coverage per pixel, plus the
per-glyph advance and ink box. That is everything the canvas needs to blend
antialiased Latin text at any size.

    python3 tools/gen_font.py > src/zui/font_data.zig
"""
import sys

from PIL import Image, ImageDraw, ImageFont

SIZE = 14  # master em size; the canvas scales from here
PAD = 2    # guard band so glyphs with negative bearings are not clipped
GLYPH_OFFSET = 32
GLYPH_COUNT = 95  # ASCII 32..126

font = ImageFont.load_default(size=SIZE)
ascent, descent = font.getmetrics()

# The rasteriser is given a canvas with a guard band — Pillow's default font has
# glyphs whose ink starts at a negative x bearing, and some whose dots sit above
# the ascender — and every metric is then read back *from the pixels*: the ink
# box is whatever the rasteriser actually drew. Deriving `left`/`top`/`w`/`h`
# from `getbbox()` instead is tempting and wrong: it answers with a layout box
# for some glyphs (a quote mark came back 11 px tall with 4 px of ink), and the
# reader walks the coverage with a stride of `w`, so a box that is one pixel too
# wide tears the glyph diagonally on screen.

CANVAS_W = int(font.getlength("M")) + 2 * PAD + 2
CANVAS_H = ascent + descent + 2 * PAD

glyphs = []
pool = bytearray()

for code in range(GLYPH_OFFSET, GLYPH_OFFSET + GLYPH_COUNT):
    ch = chr(code)
    advance = font.getlength(ch)

    canvas = Image.new("L", (CANVAS_W, CANVAS_H), 0)
    ImageDraw.Draw(canvas).text((PAD, PAD), ch, font=font, fill=255)
    box = canvas.getbbox()
    if box is None:
        # Nothing drawn: a space, or a control character. Advance only.
        glyphs.append((advance, 0, 0, 0, 0, len(pool)))
        continue

    ink = canvas.crop(box)
    w, h = ink.size
    # Bearing from the pen origin, and from the baseline (negative is above it).
    left = box[0] - PAD
    top = box[1] - (PAD + ascent)
    assert left + w <= CANVAS_W - PAD and top + h <= CANVAS_H - PAD, (ch, box)

    # The reader assumes the box is tight: assert it here rather than discover it
    # on screen. (`font.zig` asserts the same thing over the committed table.)
    pixels = ink.load()
    assert any(pixels[x, 0] for x in range(w)), ch
    assert any(pixels[x, h - 1] for x in range(w)), ch
    assert any(pixels[0, y] for y in range(h)), ch
    assert any(pixels[w - 1, y] for y in range(h)), ch

    pool.extend(ink.tobytes())
    glyphs.append((advance, left, top, w, h, len(pool) - w * h))

out = sys.stdout
out.write("//! Generated by `tools/gen_font.py` — do not edit by hand.\n")
out.write("//!\n")
out.write("//! A %d px sans-serif rasterised to 8-bit coverage: one byte per pixel in\n" % SIZE)
out.write("//! `alpha`, plus per-glyph metrics. The canvas blends these bytes, so text is\n")
out.write("//! antialiased at the master size and bilinearly sampled at any other size.\n")
out.write("//! Regenerating this file is *not* part of `zig build`.\n")
out.write("\n")
out.write("/// The size in pixels the coverage was rasterised at: the canvas scales by the\n")
out.write("/// ratio of the requested size to this.\n")
out.write("pub const em: f32 = %d;\n" % SIZE)
out.write("/// Distance from the baseline up to the top of the line box.\n")
out.write("pub const ascent: f32 = %d;\n" % ascent)
out.write("/// Distance from the baseline down to the bottom of the line box.\n")
out.write("pub const descent: f32 = %d;\n" % descent)
out.write("\n")
out.write("/// One glyph: advance width, the ink box's bearing from the pen origin (both\n")
out.write("/// scaled by the canvas), and where its coverage bytes start in `alpha`.\n")
out.write("pub const Glyph = struct {\n")
out.write("    advance: f32,\n")
out.write("    left: i16,\n")
out.write("    top: i16,\n")
out.write("    w: u16,\n")
out.write("    h: u16,\n")
out.write("    offset: u32,\n")
out.write("};\n")
out.write("\n")
out.write("/// ASCII 32..126, in order: `glyphs[ch - 32]`.\n")
out.write("pub const glyphs = [_]Glyph{\n")
for advance, left, top, w, h, off in glyphs:
    out.write(
        "    .{ .advance = %.1f, .left = %d, .top = %d, .w = %d, .h = %d, .offset = %d },\n"
        % (advance, left, top, w, h, off)
    )
out.write("};\n")
out.write("\n")
out.write("/// Coverage, `w * h` bytes per glyph, row major.\n")
out.write("pub const alpha = [_]u8{\n")
for i in range(0, len(pool), 16):
    out.write("    " + ", ".join(str(b) for b in pool[i:i + 16]) + ",\n")
out.write("};\n")
