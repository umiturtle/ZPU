//! ZAPP Font Module
//!
//! フォントレンダリングを担当するモジュール。
//! 現在は簡易的な5x7ドットフォントを実装。
//! 将来的にはTrueType/OpenTypeフォントの読み込みに対応予定。

const std = @import("std");
const zgf = @import("zgf");

/// フォントサイズ
pub const FontSize = enum {
    small,   // 8px
    medium,  // 14px (default)
    large,   // 18px
    xlarge,  // 24px
};

/// フォント設定
pub const FontConfig = struct {
    size: FontSize = .medium,
    color: zgf.Color = .{ .r = 0.9, .g = 0.9, .b = 0.9, .a = 1.0 },
    spacing: f32 = 1.0,
};

/// 文字の幅と高さを取得
pub fn getCharSize(size: FontSize) struct { w: usize, h: usize } {
    return switch (size) {
        .small => .{ .w = 4, .h = 6 },
        .medium => .{ .w = 5, .h = 7 },
        .large => .{ .w = 6, .h = 7 }, // pattern height is fixed at 7
        .xlarge => .{ .w = 8, .h = 7 }, // pattern height is fixed at 7
    };
}

