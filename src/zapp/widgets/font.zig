/// テキストをレンダリングする
pub fn renderText(fb: *zgf.Image, text: []const u8, x: f32, y: f32, config: FontConfig) void {
    const char_size = getCharSize(config.size);
    const spacing = config.spacing;
    
    var cx: usize = @intFromFloat(@max(x, 0));
    const cy: usize = @intFromFloat(@max(y, 0));
    const fw = fb.width();
    const fh = fb.height();
    
    for (text) |ch| {
        // 画面右端を超えたら描画を停止
        if (cx >= fw) break;
        
        // 文字パターンを取得
        const pattern = getCharPattern(ch);
        
        // 文字を描画
        for (0..char_size.h) |py| {
            for (0..char_size.w) |px| {
                if (pattern[py] & (@as(u8, 1) << @intCast(char_size.w - 1 - px)) != 0) {
                    const draw_x = cx + px;
                    const draw_y = cy + py;
                    if (draw_x < fw and draw_y < fh) {
                        fb.setPixel(@intCast(draw_x), @intCast(draw_y), config.color);
                    }
                }
            }
        }
        
        // 次の文字位置に進む
        cx += char_size.w + @as(usize, @intFromFloat(spacing));
    }
}

/// テキストの幅を計算する
pub fn calculateTextWidth(text: []const u8, size: FontSize, spacing: f32) f32 {
    const char_size = getCharSize(size);
    var width: f32 = 0;
    for (text) |ch| {
        if (ch == ' ') {
            width += @as(f32, @floatFromInt(char_size.w)) / 2 + spacing;
        } else {
            width += @as(f32, @floatFromInt(char_size.w)) + spacing;
        }
    }
    return width - spacing; // 最後のスペーシングを引く
}

// テスト

test "font - getCharSize small" {
    const size = getCharSize(.small);
    try std.testing.expectEqual(@as(usize, 4), size.w);
    try std.testing.expectEqual(@as(usize, 6), size.h);
}

test "font - getCharSize medium" {
    const size = getCharSize(.medium);
    try std.testing.expectEqual(@as(usize, 5), size.w);
    try std.testing.expectEqual(@as(usize, 7), size.h);
}

test "font - getCharPattern A" {
    const pattern = getCharPattern('A');
    try std.testing.expectEqual(@as(u8, 0x04), pattern[0]);
    try std.testing.expectEqual(@as(u8, 0x1F), pattern[3]);
}

test "font - renderText" {
    const alloc = std.testing.allocator;
    var img = try zgf.Image.init(alloc, 100, 20, 3);
    defer img.deinit();
    
    renderText(&img, "Hello", 5, 5, .{
        .size = .medium,
        .color = .{ .r = 1.0, .g = 1.0, .b = 1.0, .a = 1.0 },
    });
    
    const pixels = try img.toPixels(alloc);
    defer alloc.free(pixels);
    
    // テキストが描画されているはず
    try std.testing.expect(pixels.len > 0);
}

test "font - calculateTextWidth" {
    const width = calculateTextWidth("Hello", .medium, 1.0);
    // "Hello" = 5文字 × (5px + 1px) - 1px = 29px
    try std.testing.expectApproxEqAbs(@as(f32, 29.0), width, 0.1);
}
